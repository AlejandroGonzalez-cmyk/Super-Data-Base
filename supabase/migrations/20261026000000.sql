CREATE OR REPLACE FUNCTION "public"."verificar_rol_usuario"() RETURNS "text"
    LANGUAGE "sql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  -- El '(SELECT auth.uid())' optimiza el rendimiento en caché de Postgres
  SELECT rol::text 
  FROM public.usuarios 
  WHERE id_usuarios = (SELECT auth.uid())
  LIMIT 1;
$$;


